#!/usr/bin/env python3
"""Make our codec dylibs and Wine modules load from the candidate engine."""
import pathlib
import subprocess
import sys

engine = pathlib.Path(sys.argv[1]).resolve()
prefix = pathlib.Path(sys.argv[2]).resolve()
gst = engine / 'lib/gstreamer/GStreamer.framework/Versions/1.0'
lib = gst / 'lib'

def run(*args):
    return subprocess.check_output(args, text=True, stderr=subprocess.DEVNULL)

files = list(lib.glob('libav*.dylib')) + list(lib.glob('libsw*.dylib'))
files += [engine / 'lib/wine/x86_64-unix' / (name + '.so') for name in ('winedmo', 'winegstreamer')]
for path in sorted(set(p.resolve() for p in files)):
    deps = [line.strip().split(' (')[0] for line in run('otool', '-L', str(path)).splitlines()[1:]]
    for dep in deps:
        if dep.startswith(str(prefix) + '/lib/') or dep.startswith('@loader_path/../../gstreamer/'):
            basename = pathlib.Path(dep).name
            target = ('@loader_path/' if path.parent == lib else '@rpath/') + basename
            subprocess.run(['install_name_tool', '-change', dep, target, str(path)], check=True)
    if path.parent == lib:
        subprocess.run(['install_name_tool', '-id', '@rpath/' + path.name, str(path)], check=True)
    if path.suffix == '.so':
        rpath = '@loader_path/../../gstreamer/GStreamer.framework/Versions/1.0/lib'
        if rpath not in run('otool', '-l', str(path)):
            subprocess.run(['install_name_tool', '-add_rpath', rpath, str(path)], check=True)
        # Remove absolute rpaths generated by GStreamer's relocatable .pc files.
        lines = run('otool', '-l', str(path)).splitlines()
        for i, line in enumerate(lines):
            if line.strip() == 'cmd LC_RPATH':
                old = lines[i + 2].strip().split(' (offset')[0].removeprefix('path ')
                if old.startswith('/') and 'GStreamer.framework' in old:
                    subprocess.run(['install_name_tool', '-delete_rpath', old, str(path)], check=True)
    subprocess.run(['codesign', '--force', '--sign', '-', str(path)], check=True, stderr=subprocess.DEVNULL)
print('Relocated and signed our codec libraries/modules; Apple directories untouched.')
